#!/usr/bin/env python3
"""Rebind an unchanged genuine font atlas after an audited catalogue extension.

Glyph lookup is independent of packing priority. Require the exact baseline
generator/review, identical glyph requirements, coverage of newly active house
text and current field skill text, and the original binary/page fingerprints.
No new font pixels or native measurements are generated by this operation.
"""
import argparse,collections,hashlib,json,re,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from tools import source_fonts
from tools.house_presents import write_json

def require(condition,message):
    if not condition:raise ValueError(message)

def requirements(catalog,house_only=False):
    out=collections.defaultdict(set);active={r['key'] for r in catalog['house_bindings']}
    names=''.join(r['name'] for r in catalog['locales'])
    for locale in catalog['locales']:
        chars=out[locale['font']];chars.update(range(32,127));chars.update(source_fonts.scalar_text(names))
        for row in catalog['records']:
            if not house_only or row['key'] in active:chars.update(source_fonts.scalar_text(row['values'].get(locale['code'],'') or row['values'].get('en','')))
    return dict(out)

def validate_coverage(old,new,manifest,field):
    require(requirements(old)==requirements(new),'Catalogue requires different glyphs; regenerate with genuine tools')
    previous=requirements(old,True);current=requirements(new,True)
    available={f['source']:{g['codepoint'] for g in manifest['glyphs'][f['first_glyph']:f['first_glyph']+f['glyph_count']]} for f in manifest['faces']}
    for source,chars in current.items():require(chars-previous[source]<=available[source],'Newly active house text lacks reviewed font glyphs')
    locale_fonts={r['code']:r['font'] for r in new['locales']}
    for skill in field['skills']:
        for key in ('names','descriptions','max_message','up_message'):
            for locale,text in skill[key].items():require(source_fonts.scalar_text(text)<=available[locale_fonts[locale]],'Field skill text lacks reviewed font glyphs')

def main():
    p=argparse.ArgumentParser();p.add_argument('--base',required=True);a=p.parse_args()
    require(re.fullmatch('[0-9a-f]{40}',a.base) is not None,'Use an exact reviewed baseline commit')
    old=lambda path:subprocess.check_output(['git','show',a.base+':'+path],cwd=ROOT)
    path='content/asset-receipts/fonts/source.json';catalog_path='content/native-localization.json'
    manifest=json.loads(old(path));before=(ROOT/path).read_bytes();old_catalog=old(catalog_path);catalog=(ROOT/catalog_path).read_bytes()
    sha=lambda b:hashlib.sha256(b).hexdigest()
    require(manifest['catalog_sha256']==sha(old_catalog) and manifest['generator_sha256']==source_fonts.sha(ROOT/'tools/source_fonts.py'),
            'Original font catalogue/generator proof differs')
    current=json.loads(before);require({k:v for k,v in current.items() if k!='catalog_sha256'}=={k:v for k,v in manifest.items() if k!='catalog_sha256'},'Original font atlas/metrics/review changed')
    require(manifest['review']==json.loads((ROOT/'content/source-fonts-review.json').read_bytes()),'Reviewed source font identities changed')
    validate_coverage(json.loads(old_catalog),json.loads(catalog),manifest,json.loads((ROOT/'content/native-field-equipment.json').read_bytes()))
    candidate=dict(manifest,catalog_sha256=sha(catalog))
    try:
        write_json(ROOT/path,candidate);source_fonts.stage_files(ROOT/'romfs')
    except Exception:
        (ROOT/path).write_bytes(before);raise
    write_json(ROOT/'content/font-catalog-reuse.json',dict(schema=1,baseline_commit=a.base,original_receipt_sha256=sha(old(path)),
        receipt_sha256=source_fonts.sha(ROOT/path),catalog_sha256=sha(catalog),generator_unchanged=True,glyph_requirements_unchanged=True,
        newly_active_text_covered=True,binary_and_pages_verified=True,scope='Existing original glyph pixels, native advances and atlas packing retained; catalogue bindings only'))
    print('Original source font atlases retained: unchanged generator/review/requirements; all newly active text and actual binary/page fingerprints checked')
    return 0
if __name__=='__main__':raise SystemExit(main())
